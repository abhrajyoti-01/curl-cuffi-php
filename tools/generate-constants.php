<?php
/**
 * Generates src/Curl/Const/*.php from curl_cffi's const.py so the constant
 * values stay identical to the Python library.
 *
 * Usage: php tools/generate-constants.php /path/to/curl_cffi/const.py
 *
 * This is a development tool only. The library never needs Python at runtime.
 */

declare(strict_types=1);

$source = $argv[1] ?? null;
if ($source === null || !is_file($source)) {
    fwrite(STDERR, "Usage: php tools/generate-constants.php /path/to/curl_cffi/const.py\n");
    exit(1);
}

$outDir = dirname(__DIR__) . '/src/Curl/Const';
$lines = file($source, FILE_IGNORE_NEW_LINES);
$classes = [];
$current = null;

foreach ($lines as $line) {
    if (preg_match('/^class (\w+)\(IntEnum\):/', $line, $m)) {
        $current = $m[1];
        $classes[$current] = ['doc' => '', 'consts' => []];
        continue;
    }
    if ($current === null) {
        continue;
    }
    if ($classes[$current]['doc'] === '' && preg_match('/^\s+"""(.*?)(""")?$/', $line, $m)) {
        $classes[$current]['doc'] = trim(str_replace(['``', '"""'], ['`', ''], $m[1]));
        continue;
    }
    if (preg_match('/^\s+([A-Za-z_]\w*)\s*=\s*locals\(\)\.get\("(\w+)"\)/', $line, $m)) {
        // Python alias such as FILE = WRITEDATA.
        $target = $classes[$current]['consts'][$m[2]] ?? null;
        if ($target !== null) {
            $classes[$current]['consts'][$m[1]] = [$target[0], $m[2], "alias of {$m[2]}"];
        }
        continue;
    }
    if (preg_match('/^    ([A-Za-z_][A-Za-z0-9_]*)\s*=\s*([^#]+?)\s*(#\s*(.*))?$/', $line, $m)) {
        $expr = trim($m[2]);
        if (!preg_match('/^[0-9xXa-fA-F\s+<()*-]+$/', $expr)) {
            continue;
        }
        $value = evaluate($expr);
        $classes[$current]['consts'][$m[1]] = [$value, $expr, $m[4] ?? ''];
    }
}

function evaluate(string $expr): int
{
    $expr = trim($expr);
    if (preg_match('/^\((.*)\)$/', $expr, $m)) {
        return evaluate($m[1]);
    }
    if (preg_match('/^(.+?)\s*\+\s*(.+)$/', $expr, $m)) {
        return evaluate($m[1]) + evaluate($m[2]);
    }
    if (preg_match('/^(.+?)\s*<<\s*(.+)$/', $expr, $m)) {
        return evaluate($m[1]) << evaluate($m[2]);
    }
    if (preg_match('/^-?0[xX][0-9a-fA-F]+$/', $expr)) {
        return intval($expr, 16);
    }
    if (preg_match('/^-?\d+$/', $expr)) {
        return (int) $expr;
    }
    throw new RuntimeException("Cannot evaluate constant expression: $expr");
}

foreach ($classes as $name => $info) {
    $body = '';
    foreach ($info['consts'] as $const => [$value, $expr, $comment]) {
        $c = $comment !== '' ? ' // ' . trim($comment) : '';
        $body .= "    public const {$const} = {$value};{$c}\n";
    }
    $doc = $info['doc'] !== '' ? $info['doc'] : "{$name} constants from libcurl.";
    $php = <<<PHP
<?php

declare(strict_types=1);

namespace CurlCffi\\Curl\\Const;

/**
 * {$doc}
 *
 * Generated by tools/generate-constants.php from curl_cffi's const.py. Do not edit by hand.
 */
final class {$name}
{
{$body}
    /** @return array<string, int> all constants of this class, name => value */
    public static function all(): array
    {
        return (new \\ReflectionClass(self::class))->getConstants();
    }

    /** Returns the first constant name with this value, or null. */
    public static function nameOf(int \$value): ?string
    {
        \$name = array_search(\$value, self::all(), true);

        return \$name === false ? null : \$name;
    }
}

PHP;
    file_put_contents("{$outDir}/{$name}.php", $php);
    printf("%-16s %4d constants\n", $name, count($info['consts']));
}
